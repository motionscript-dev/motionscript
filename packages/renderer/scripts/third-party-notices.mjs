// Writes THIRD_PARTY_NOTICES.txt: every crate compiled into
// ms_renderer_bg.wasm with its licence text, from cargo-about (about.toml
// holds the accepted licences). `--check` exits 1 when the file is stale.
//
//   cargo install cargo-about --version 0.9.3 --features cli --locked
//   node scripts/third-party-notices.mjs [--check]

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const CARGO_ABOUT = "0.9.3";
const root = fileURLToPath(new URL("..", import.meta.url));
const target = join(root, "THIRD_PARTY_NOTICES.txt");
const check = process.argv.includes("--check");

const run = (args) => execFileSync("cargo", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] });

const version = run(["about", "--version"]).trim().split(" ").pop();
if (version !== CARGO_ABOUT) {
    console.error(`cargo-about ${version} found; the notices are generated with ${CARGO_ABOUT}:`);
    console.error(`  cargo install cargo-about --version ${CARGO_ABOUT} --features cli --locked`);
    process.exit(1);
}

// cargo-about reads metadata for every platform, so every platform's crates must be on disk.
run(["fetch", "--locked"]);
const dir = mkdtempSync(join(tmpdir(), "ms-notices-"));
const out = join(dir, "notices.txt");
try {
    run(["about", "generate", "--frozen", "-m", "crates/renderer/Cargo.toml", "-c", "about.toml", "scripts/third-party-notices.hbs", "-o", out]);
    var body = readFileSync(out, "utf8");
} finally {
    rmSync(dir, { recursive: true, force: true });
}

const header = `Third-party notices for @motionscript/renderer

dist/ms_renderer_bg.wasm is Motion Script's renderer (crates/ in the source
repository, Apache-2.0, LICENSE in this package) compiled to WebAssembly with
the Rust crates below, and dist/index.js carries the bindings wasm-bindgen
generates for it. Each crate remains under its own licence; where a crate
offers a choice, the first of MIT, Apache-2.0 and Zlib is the one used here.
Generated by scripts/third-party-notices.mjs; do not edit.

Licences, by the number of crates under each:
`;

const text = (header + body)
    .replace(/\r\n?/g, "\n")
    .replace(/[ \t]+$/gm, "")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd() + "\n";

if (check) {
    let current = "";
    try {
        current = readFileSync(target, "utf8").replace(/\r\n?/g, "\n");
    } catch {}
    if (current !== text) {
        console.error("THIRD_PARTY_NOTICES.txt is stale: run `pnpm --filter @motionscript/renderer notices`.");
        process.exit(1);
    }
    console.log("THIRD_PARTY_NOTICES.txt is current.");
} else {
    writeFileSync(target, text);
    console.log(`Wrote ${target}`);
}
