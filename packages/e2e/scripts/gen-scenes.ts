/**
 * Regenerate the scene catalog from src/scenes/catalog.json.
 *
 * catalog.json is the list of scenes — id, section and description, in the order
 * the harness shoots them. For each entry this ensures a scene file exists at
 * src/scenes/<id>.ts (a placeholder stub when missing; existing files are never
 * touched) and (re)writes src/scenes/catalog.ts, which pairs every entry with a
 * loader for its document. Adding a scene is adding an entry, then running this.
 *
 * Run from the e2e package root:  pnpm gen
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { pascalCase } from './lib/scene-name.ts';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(__dirname, '..');
const scenesDir = path.join(pkgRoot, 'src', 'scenes');
const catalogJson = path.join(scenesDir, 'catalog.json');

type Entry = { id: string; section: string; description: string };

const stub = (id: string) => `import { placeholder } from './_lib';

// TODO: replace this placeholder with a real scene exercising \`${id}\`.
export default placeholder('${id}');
`;

function main(): void {
    const entries = JSON.parse(fs.readFileSync(catalogJson, 'utf8')) as Entry[];
    if (entries.length === 0) throw new Error(`No scenes listed in ${catalogJson}.`);

    // Guard against duplicate ids (they would collide as filenames and track ids).
    const seen = new Set<string>();
    for (const e of entries) {
        if (seen.has(e.id)) throw new Error(`Duplicate scene id in catalog.json: ${e.id}`);
        seen.add(e.id);
    }

    let created = 0;
    for (const { id } of entries) {
        const file = path.join(scenesDir, `${id}.ts`);
        if (fs.existsSync(file)) continue;
        fs.writeFileSync(file, stub(id), 'utf8');
        created++;
    }

    const rows = entries
        .map(
            ({ id, section, description }) =>
                `    { id: ${JSON.stringify(id)}, name: ${JSON.stringify(pascalCase(id))}, ` +
                `section: ${JSON.stringify(section)}, description: ${JSON.stringify(description)}, ` +
                `load: () => import('./${id}') },`,
        )
        .join('\n');

    const catalog = `// AUTO-GENERATED by scripts/gen-scenes.ts from catalog.json — do not edit by hand.
// Run \`pnpm gen\` in this package to regenerate.
/* eslint-disable */
import type { CompositionDocument } from '@motionscript/sdk';

export interface SceneEntry {
    /** The scene id, e.g. "rect-basic" — also its filename and track id. */
    id: string;
    /** PascalCase of the id; \`--scenes\` matches it as well as the id. */
    name: string;
    /** The section the scene belongs to, e.g. "Geometry". */
    section: string;
    description: string;
    /** The scene's document. Loaded per scene, so one that fails to build fails alone. */
    load: () => Promise<{ default: CompositionDocument }>;
}

/** Every e2e scene, in shooting order. */
export const catalog: SceneEntry[] = [
${rows}
];
`;
    fs.writeFileSync(path.join(scenesDir, 'catalog.ts'), catalog, 'utf8');

    console.log(`Catalog: ${entries.length} scenes (${created} stub(s) created).`);
}

main();
